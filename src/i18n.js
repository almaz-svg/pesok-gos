export function languageOf(ctx) {
  return ctx.state.language === 'kk' ? 'kk' : 'ru';
}

export function copyFor(ctx) {
  return messages[languageOf(ctx)];
}

export function formatDate(value, language = 'ru') {
  const date = value ? new Date(value) : null;
  return date && !Number.isNaN(date.getTime())
    ? new Intl.DateTimeFormat(language === 'kk' ? 'kk-KZ' : 'ru-RU', { timeZone: 'Asia/Almaty' }).format(date)
    : messages[language].dateMissing;
}

